// This test is mostly AI generated.

import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import ExperimentalAiPage from './page';

const mockCreateSession = vi.hoisted(() => vi.fn());
const mockGetCapabilities = vi.hoisted(() => vi.fn());
const mockStreamMessage = vi.hoisted(() => vi.fn());
const mockGenerateYaml = vi.hoisted(() => vi.fn(() => 'description: current schedule\n'));
const mockApproveProposal = vi.hoisted(() => vi.fn());
const mockRejectProposal = vi.hoisted(() => vi.fn());
const mockUpdateSessionSchedule = vi.hoisted(() => vi.fn());
const mockLoadFromYaml = vi.hoisted(() => vi.fn());

vi.mock('./aiClient', () => ({
  createSession: mockCreateSession,
  getCapabilities: mockGetCapabilities,
  streamMessage: mockStreamMessage,
  approveProposal: mockApproveProposal,
  rejectProposal: mockRejectProposal,
  updateSessionSchedule: mockUpdateSessionSchedule,
}));

vi.mock('@/utils/yamlGenerator', () => ({
  generateYamlFromState: mockGenerateYaml,
}));

vi.mock('@/hooks/useSchedulingData', () => ({
  useSchedulingData: () => ({
    apiVersionData: 'alpha',
    descriptionData: 'current schedule',
    dateData: { items: [], groups: [], range: {} },
    peopleData: { items: [], groups: [] },
    shiftTypeData: { items: [], groups: [] },
    preferences: [],
    exportData: undefined,
    filterAutoGeneratedState: (state: unknown) => state,
    loadFromYaml: mockLoadFromYaml,
  }),
}));

describe('ExperimentalAiPage', () => {
  beforeEach(() => {
    mockCreateSession.mockReset().mockResolvedValue('session-id');
    mockGetCapabilities.mockReset().mockResolvedValue({
      image_attachments: {
        enabled: false,
        accepted_media_types: ['image/jpeg', 'image/png', 'image/webp'],
        max_files: 4,
        max_bytes_per_file: 5_000_000,
      },
      document_attachments: {
        enabled: false,
        accepted_extensions: ['.txt', '.md', '.csv', '.pdf', '.xlsx'],
        max_files: 4,
        max_bytes_per_file: 5_000_000,
      },
    });
    mockStreamMessage.mockReset().mockImplementation(async (
      _sessionId: string,
      _message: string,
      callbacks: { onDelta: (text: string) => void },
    ) => {
      callbacks.onDelta('Alice');
      callbacks.onDelta(' works Monday.');
    });
    mockGenerateYaml.mockClear();
    mockApproveProposal.mockReset().mockResolvedValue('description: proposed schedule\n');
    mockRejectProposal.mockReset().mockResolvedValue(undefined);
    mockUpdateSessionSchedule.mockReset().mockResolvedValue(undefined);
    mockLoadFromYaml.mockReset();
  });

  it('sends a question with the current schedule and renders streamed text', async () => {
    const user = userEvent.setup();
    render(<ExperimentalAiPage />);

    expect(screen.getByText('Current snapshot: 0 people, 0 dates. Captured when you send the first question.')).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Experimental AI documentation' })).toHaveAttribute(
      'href',
      '/docs/user-guide/experimental-ai/',
    );
    await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'Who works Monday?');
    await user.click(screen.getByRole('button', { name: 'Send' }));

    expect(await screen.findByText('Alice works Monday.')).toBeInTheDocument();
    expect(mockCreateSession).toHaveBeenCalledWith('description: current schedule\n');
    expect(mockStreamMessage).toHaveBeenCalledWith(
      'session-id',
      'Who works Monday?',
      expect.any(Object),
      expect.any(AbortSignal),
      { images: [], documents: [] },
    );
  });

  it('previews and sends images when the backend enables them', async () => {
    mockGetCapabilities.mockResolvedValueOnce({
      image_attachments: {
        enabled: true,
        accepted_media_types: ['image/png'],
        max_files: 2,
        max_bytes_per_file: 1000,
      },
      document_attachments: {
        enabled: false,
        accepted_extensions: ['.txt', '.md', '.csv', '.pdf', '.xlsx'],
        max_files: 4,
        max_bytes_per_file: 5_000_000,
      },
    });
    const createObjectUrl = vi.spyOn(URL, 'createObjectURL').mockReturnValue('blob:image-preview');
    const revokeObjectUrl = vi.spyOn(URL, 'revokeObjectURL').mockImplementation(() => undefined);
    const user = userEvent.setup();
    const image = new File(['png'], 'ward.png', { type: 'image/png' });
    render(<ExperimentalAiPage />);

    const input = await screen.findByLabelText('Attach files');
    await user.upload(input, image);
    expect(screen.getByAltText('Preview of ward.png')).toBeInTheDocument();
    await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'What is shown?');
    await user.click(screen.getByRole('button', { name: 'Send' }));

    expect(mockStreamMessage).toHaveBeenCalledWith(
      'session-id',
      'What is shown?',
      expect.any(Object),
      expect.any(AbortSignal),
      { images: [image], documents: [] },
    );
    expect(screen.getByText('Attached: ward.png')).toBeInTheDocument();
    expect(createObjectUrl).toHaveBeenCalledWith(image);
    expect(revokeObjectUrl).toHaveBeenCalledWith('blob:image-preview');
  });

  it('previews and sends text documents when the backend enables them', async () => {
    mockGetCapabilities.mockResolvedValueOnce({
      image_attachments: {
        enabled: false,
        accepted_media_types: ['image/png'],
        max_files: 2,
        max_bytes_per_file: 1000,
      },
      document_attachments: {
        enabled: true,
        accepted_extensions: ['.txt', '.md', '.csv', '.pdf', '.xlsx'],
        max_files: 2,
        max_bytes_per_file: 5_000_000,
      },
    });
    const user = userEvent.setup();
    const document = new File(['name,shift\nAlice,day\n'], 'staff.csv', { type: '' });
    render(<ExperimentalAiPage />);

    const input = await screen.findByLabelText('Attach files');
    await user.upload(input, document);
    expect(screen.getByText('csv')).toBeInTheDocument();
    await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'Check the CSV.');
    await user.click(screen.getByRole('button', { name: 'Send' }));

    expect(mockStreamMessage).toHaveBeenCalledWith(
      'session-id',
      'Check the CSV.',
      expect.any(Object),
      expect.any(AbortSignal),
      {
        images: [],
        documents: [expect.objectContaining({ name: 'staff.csv', type: 'text/csv' })],
      },
    );
    expect(screen.getByText('Attached: staff.csv')).toBeInTheDocument();
  });

  it('normalizes PDF and XLSX media types before upload', async () => {
    mockGetCapabilities.mockResolvedValueOnce({
      image_attachments: {
        enabled: false,
        accepted_media_types: [],
        max_files: 2,
        max_bytes_per_file: 1000,
      },
      document_attachments: {
        enabled: true,
        accepted_extensions: ['.pdf', '.xlsx'],
        max_files: 2,
        max_bytes_per_file: 5_000_000,
      },
    });
    const user = userEvent.setup();
    const pdf = new File(['pdf'], 'notes.pdf', { type: '' });
    const workbook = new File(['xlsx'], 'coverage.xlsx', { type: '' });
    render(<ExperimentalAiPage />);

    const input = await screen.findByLabelText('Attach files');
    await user.upload(input, [pdf, workbook]);
    await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'Read both files.');
    await user.click(screen.getByRole('button', { name: 'Send' }));

    expect(mockStreamMessage).toHaveBeenCalledWith(
      'session-id',
      'Read both files.',
      expect.any(Object),
      expect.any(AbortSignal),
      {
        images: [],
        documents: [
          expect.objectContaining({ name: 'notes.pdf', type: 'application/pdf' }),
          expect.objectContaining({
            name: 'coverage.xlsx',
            type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
          }),
        ],
      },
    );
  });

  it('shows an error when capability discovery fails', async () => {
    mockGetCapabilities.mockRejectedValueOnce(new TypeError('Failed to fetch'));

    render(<ExperimentalAiPage />);

    expect(await screen.findByRole('alert')).toHaveTextContent(
      'Could not load AI capabilities. Check that the AI backend is reachable from this browser, then reload the page.',
    );
    expect(screen.queryByLabelText('Attach files')).not.toBeInTheDocument();
    expect(screen.getByRole('textbox', { name: 'Ask about the current schedule' })).toBeEnabled();
  });

  it('animates the thinking indicator while awaiting the first response token', async () => {
    let finishStream: (() => void) | undefined;
    mockStreamMessage.mockImplementationOnce(() => new Promise<void>(resolve => {
      finishStream = resolve;
    }));
    const user = userEvent.setup();
    render(<ExperimentalAiPage />);

    await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'Think about this.');
    await user.click(screen.getByRole('button', { name: 'Send' }));

    const thinking = await screen.findByRole('status', { name: 'Thinking' });
    expect(thinking.querySelectorAll('[style*="animation-delay"]')).toHaveLength(3);

    finishStream?.();
    await waitFor(() => expect(screen.queryByRole('status', { name: 'Thinking' })).not.toBeInTheDocument());
  });

  it('shows backend failures without discarding the user question', async () => {
    const providerError = 'The AI provider returned HTTP 525. Error ID: 72dc8f31-45af-410d-9fc2-41bdf1fc718f.';
    mockStreamMessage.mockRejectedValueOnce(new Error(providerError));
    const user = userEvent.setup();
    render(<ExperimentalAiPage />);

    await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'Can you help?');
    await user.click(screen.getByRole('button', { name: 'Send' }));

    const alert = await screen.findByRole('alert');
    expect(alert).toHaveTextContent(providerError);
    expect(screen.getByText('Can you help?')).toBeInTheDocument();
  });

  describe('proposals', () => {
    const proposingStream = (
      _sessionId: string,
      _message: string,
      callbacks: {
        onDelta: (text: string) => void;
        onReasoning?: (text: string) => void;
        onTool?: (activity: { name: string; arguments: string; result: string; ok: boolean }) => void;
        onScheduleChange?: (scheduleYaml: string) => void;
        onProposal?: (diff: string) => void;
      },
    ) => {
      callbacks.onReasoning?.('Looking at P1. ');
      callbacks.onTool?.({
        name: 'bash',
        arguments: JSON.stringify({ command: "sed -i 's/old/new/' schedule.yaml" }),
        result: 'exit_code: 0',
        ok: true,
      });
      callbacks.onScheduleChange?.('description: Head');
      callbacks.onDelta('I propose renaming P1.');
      callbacks.onProposal?.('- people.items[0].description: "" -> "Head"');
    };

    const ask = async (user: ReturnType<typeof userEvent.setup>) => {
      await user.type(screen.getByRole('textbox', { name: 'Ask about the current schedule' }), 'Rename P1.');
      await user.click(screen.getByRole('button', { name: 'Send' }));
    };

    beforeEach(() => {
      mockStreamMessage.mockReset().mockImplementation(proposingStream);
    });

    it('shows the proposed change and what the assistant did', async () => {
      const user = userEvent.setup();
      render(<ExperimentalAiPage />);

      await ask(user);

      expect(await screen.findByRole('region', { name: 'Proposed schedule change' })).toBeInTheDocument();
      expect(screen.getByText('- people.items[0].description: "" -> "Head"')).toBeInTheDocument();
      expect(screen.getByText('bash')).toBeInTheDocument();
      expect(screen.getByText('schedule edit')).toBeInTheDocument();
      expect(screen.getByText(/^Reasoning ·/)).toBeInTheDocument();
    });

    it('applies an approved proposal as one history entry', async () => {
      const user = userEvent.setup();
      render(<ExperimentalAiPage />);
      await ask(user);

      await user.click(await screen.findByRole('button', { name: 'Approve' }));

      await waitFor(() => expect(mockLoadFromYaml).toHaveBeenCalledTimes(1));
      expect(mockApproveProposal).toHaveBeenCalledWith('session-id', 'description: current schedule\n');
      expect(mockLoadFromYaml).toHaveBeenCalledWith({ description: 'proposed schedule' });
      expect(screen.queryByRole('region', { name: 'Proposed schedule change' })).not.toBeInTheDocument();
      expect(screen.getByText('The proposed schedule was applied. Undo reverts it in one step.')).toBeInTheDocument();
    });

    it('reports a proposal that no longer matches the current schedule', async () => {
      mockApproveProposal.mockRejectedValue(new Error('The schedule changed after this proposal was created.'));
      const user = userEvent.setup();
      render(<ExperimentalAiPage />);
      await ask(user);

      await user.click(await screen.findByRole('button', { name: 'Approve' }));

      expect(await screen.findByText('The schedule changed after this proposal was created.')).toBeInTheDocument();
      expect(mockLoadFromYaml).not.toHaveBeenCalled();
    });

    it('drops a rejected proposal', async () => {
      const user = userEvent.setup();
      render(<ExperimentalAiPage />);
      await ask(user);

      await user.click(await screen.findByRole('button', { name: 'Reject' }));

      await waitFor(() => expect(mockRejectProposal).toHaveBeenCalledWith('session-id'));
      expect(screen.queryByRole('region', { name: 'Proposed schedule change' })).not.toBeInTheDocument();
      expect(mockLoadFromYaml).not.toHaveBeenCalled();
    });

    it('sends a changed schedule to an existing session before the next question', async () => {
      const user = userEvent.setup();
      render(<ExperimentalAiPage />);
      await ask(user);
      mockGenerateYaml.mockReturnValue('description: edited elsewhere\n');

      await ask(user);

      await waitFor(() => expect(mockUpdateSessionSchedule).toHaveBeenCalledWith(
        'session-id',
        'description: edited elsewhere\n',
      ));
      expect(mockCreateSession).toHaveBeenCalledTimes(1);
    });
  });
});
