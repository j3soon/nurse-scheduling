import { loadLegacyScheduleSpec } from '@/compat/scheduleSpec';
import { INFINITY_PLACEHOLDER, NEGATIVE_INFINITY_PLACEHOLDER, STORAGE_KEY, WORKER_NAMESPACE_KEY } from './schedulingConstants';
import { createDefaultHistoryState, HistoryState } from './schedulingHistory';
import { filterAutoGeneratedState, normalizeStateForFrontend } from './schedulingGeneratedData';

// A stored string equal to a placeholder would otherwise come back as a number,
// so an escape prefix is added on the way out and removed on the way in. The
// prefix repeats, which keeps an already-escaped string reversible too.
const PLACEHOLDER_ESCAPE_PREFIX = '__ESCAPED__';
const PLACEHOLDER_PATTERN = new RegExp(
  `^(?:${PLACEHOLDER_ESCAPE_PREFIX})*(?:${INFINITY_PLACEHOLDER}|${NEGATIVE_INFINITY_PLACEHOLDER})$`
);

// Helper function to convert infinity/-infinity values to safe string representations
export function replaceInfinityValues(obj: unknown): unknown {
  if (obj === null || typeof obj !== 'object') {
    if (obj === Infinity) return INFINITY_PLACEHOLDER;
    if (obj === -Infinity) return NEGATIVE_INFINITY_PLACEHOLDER;
    if (typeof obj === 'string' && PLACEHOLDER_PATTERN.test(obj)) return PLACEHOLDER_ESCAPE_PREFIX + obj;
    return obj;
  }

  if (Array.isArray(obj)) {
    return obj.map(replaceInfinityValues);
  }

  const entries = Object.entries(obj as Record<string, unknown>);
  return Object.fromEntries(entries.map(([key, value]) => [key, replaceInfinityValues(value)]));
}

// Helper function to restore infinity/-infinity values from safe string representations
export function restoreInfinityValues(obj: unknown): unknown {
  if (obj === null || typeof obj !== 'object') {
    if (obj === INFINITY_PLACEHOLDER) return Infinity;
    if (obj === NEGATIVE_INFINITY_PLACEHOLDER) return -Infinity;
    if (typeof obj === 'string' && obj.startsWith(PLACEHOLDER_ESCAPE_PREFIX) && PLACEHOLDER_PATTERN.test(obj)) {
      return obj.slice(PLACEHOLDER_ESCAPE_PREFIX.length);
    }
    return obj;
  }

  if (Array.isArray(obj)) {
    return obj.map(restoreInfinityValues);
  }

  const entries = Object.entries(obj as Record<string, unknown>);
  return Object.fromEntries(entries.map(([key, value]) => [key, restoreInfinityValues(value)]));
}

export function loadStateFromStorage(): HistoryState {
  if (typeof window === 'undefined') return createDefaultHistoryState();

  try {
    const stored = localStorage.getItem(getStorageKey());

    if (stored === null) return loadLegacyScheduleSpec(localStorage, getStorageKey(), decodeHistoryState) ?? createDefaultHistoryState();
    return decodeHistoryState(stored);
  } catch (error) {
    console.error('Failed to load Schedule Spec from localStorage:', error);
    return createDefaultHistoryState();
  }
}

function decodeHistoryState(stored: string): HistoryState {
  const parsedHistoryState = restoreInfinityValues(JSON.parse(stored)) as Omit<HistoryState, 'currentHistoryIndex'> & {
    currentHistoryIndex?: unknown;
  };

  for (const state of [...parsedHistoryState.history, parsedHistoryState.state]) {
    state.dates.range.startDate = state.dates.range.startDate ? new Date(state.dates.range.startDate) : undefined;
    state.dates.range.endDate = state.dates.range.endDate ? new Date(state.dates.range.endDate) : undefined;
  }

  const currentState = normalizeStateForFrontend(parsedHistoryState.state);
  const lastIndex = Math.max(0, parsedHistoryState.history.length - 1);
  const storedIndex = parsedHistoryState.currentHistoryIndex;
  const currentHistoryIndex = typeof storedIndex === 'number' && Number.isInteger(storedIndex)
    ? Math.max(0, Math.min(storedIndex, lastIndex))
    : lastIndex;

  return {
    state: currentState,
    history: parsedHistoryState.history.map(normalizeStateForFrontend),
    currentHistoryIndex
  };
}

export function saveStateToStorage(historyState: HistoryState): void {
  if (typeof window === 'undefined') return;

  try {
    // Store the complete history state, but exclude auto-generated groups and computed date items
    const historyStateToStore = {
      state: {
        ...filterAutoGeneratedState(historyState.state),
        dates: {
          ...filterAutoGeneratedState(historyState.state).dates,
          range: {
            startDate: historyState.state.dates.range.startDate?.toISOString().split('T')[0],
            endDate: historyState.state.dates.range.endDate?.toISOString().split('T')[0]
          },
          items: undefined  // Don't store computed items
        }
      },
      history: historyState.history.map(state => ({
        ...filterAutoGeneratedState(state),
        dates: {
          ...filterAutoGeneratedState(state).dates,
          range: {
            startDate: state.dates.range.startDate?.toISOString().split('T')[0],
            endDate: state.dates.range.endDate?.toISOString().split('T')[0]
          },
          items: undefined  // Don't store computed items
        }
      })),
      currentHistoryIndex: historyState.currentHistoryIndex
    };

    // Replace infinity values with safe placeholders before JSON.stringify
    const safeHistoryState = replaceInfinityValues(historyStateToStore);
    localStorage.setItem(getStorageKey(), JSON.stringify(safeHistoryState));
  } catch (error) {
    console.error('Failed to save data to localStorage:', error);
  }
}

export function getStorageKey(): string {
  if (typeof window === 'undefined') return STORAGE_KEY;

  const workerNamespace = (window as unknown as { [WORKER_NAMESPACE_KEY]?: string })[WORKER_NAMESPACE_KEY];
  return workerNamespace ? `${STORAGE_KEY}__${workerNamespace}` : STORAGE_KEY;
}
